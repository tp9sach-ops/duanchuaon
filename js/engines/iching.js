export const HEXAGRAMS = DATA.map(d => {
  const lower = TRI[d.bin.slice(0, 3)], upper = TRI[d.bin.slice(3, 6)];
  return {
    number: d.n, name: d.name, binary: d.bin, lines: [...d.bin].map(Number),
    lower: lower[0], lowerImage: lower[1], upper: upper[0], upperImage: upper[1],
    level: d.level, judgment: d.judgment, meaning: d.meaning, advice: d.advice, topics: d.t,
  };
});

const BY_BINARY = new Map();
for (const hex of HEXAGRAMS) {
  if (hex.number < 1 || hex.number > 64) throw new Error(`Kinh Dịch: số quẻ không hợp lệ (${hex.number})`);
  if (BY_BINARY.has(hex.binary)) throw new Error(`Kinh Dịch: trùng quẻ ${hex.name}`);
  if (!hex.name.startsWith('Thuần ') && !hex.name.startsWith(`${hex.upperImage} ${hex.lowerImage} `))
    throw new Error(`Kinh Dịch: tên quẻ ${hex.number} không khớp thượng/hạ quái (${hex.name})`);
  for (const key of Object.keys(TOPICS)) if (!hex.topics[key]) throw new Error(`Kinh Dịch: quẻ ${hex.number} thiếu luận giải ${key}`);
  BY_BINARY.set(hex.binary, hex);
}
if (BY_BINARY.size !== 64) throw new Error('Kinh Dịch: phải có đủ 64 quẻ');

const strip = s => String(s || '').toLowerCase().normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').replace(/[^a-z0-9\s]/g, ' ')
  .replace(/\s+/g, ' ').trim();

const TOPIC_WORDS = {
  taiLoc: ['tai loc', 'tien bac', 'tien te', 'tien', 'giau', 'phat tai', 'lam an', 'buon ban', 'kinh doanh', 'dau tu', 'loi nhuan', 'thu nhap'],
  tinhDuyen: ['tinh duyen', 'tinh cam', 'tinh yeu', 'nguoi yeu', 'vo chong', 'vo toi', 'chong toi', 'hon nhan', 'ket hon', 'duyen', 'ban trai', 'ban gai', 'yeu nhau', 'dang yeu'],
  congDanh: ['cong danh', 'su nghiep', 'cong viec', 'viec lam', 'thi cu', 'ky thi', 'di thi', 'hoc hanh', 'hoc', 'phong van', 'thang tien', 'de bat', 'cong ty', 'tuyen dung', 'do dat'],
  sucKhoe: ['suc khoe', 'benh', 'om', 'bi dau', 'dau dau', 'dau bung', 'dau lung', 'dau rang', 'chua benh', 'kham benh', 'than the', 'tai nan', 'sinh ly', 'bac si'],
};
export function detectTopic(text) {
  const s = ` ${strip(text)} `;
  let best = null, bestHits = 0, bestPos = Infinity;
  for (const [key, words] of Object.entries(TOPIC_WORDS)) {
    let hits = 0, first = Infinity;
    for (const w of new Set(words)) {
      const at = s.indexOf(` ${w} `);
      if (at >= 0) { hits++; first = Math.min(first, at); }
    }
    if (!hits) continue;
    if (hits > bestHits || (hits === bestHits && first < bestPos)) { best = key; bestHits = hits; bestPos = first; }
  }
  return best;
}

export function drawReading(text, rng = Math.random) {
  const lines = [];
  for (let i = 0; i < 6; i++) lines.push(rng() < 0.5 ? 1 : 0);
  const hex = BY_BINARY.get(lines.join(''));
  const key = detectTopic(text);
  return {
    number: hex.number,
    name: hex.name,
    glyph: String.fromCodePoint(0x4dc0 + hex.number - 1),
    upper: hex.upper, upperImage: hex.upperImage,
    lower: hex.lower, lowerImage: hex.lowerImage,
    lines,
    level: hex.level,
    judgment: hex.judgment,
    meaning: hex.meaning,
    advice: hex.advice,
    topic: key ? { key, label: TOPICS[key], text: hex.topics[key] } : null,
  };
}
