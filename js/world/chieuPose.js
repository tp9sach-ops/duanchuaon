/** Thời lượng khung PHÁT (giây); chiêu không ghi dùng 0,2. Chiêu lao/ngắn nhanh hơn; Tuyệt học dài hơn để thấy hình bóng. */
export const PHAT = { kim_1: 0.15, kim_3: 0.35, kim_tuyet: 0.4, moc_anthan_4: 0.15, moc_tuyet: 0.4, thuy_tuyet: 0.4, tho_tuyet: 0.3, hoa_hoalong_4: 0.4, hoa_tuyet: 0.4 };
const PHAT_MAC_DINH = 0.2, THU_MIN = 0.25, THU_MAX = 0.8;

export const hasCast = (id) => typeof id === 'string' && Object.prototype.hasOwnProperty.call(POSE, id) && !!chieuOf(id);

/** Lịch ba khung của chiêu `id`: { gong, phat, thu, tong } (giây); chiêu lạ → null. */
export function castTimeline(id) {
  if (!hasCast(id)) return null;
  const c = chieuOf(id), gong = c.gong, phat = PHAT[id] || PHAT_MAC_DINH, thu = clamp(c.hauDong || 0, THU_MIN, THU_MAX);
  return { gong, phat, thu, tong: Math.round((gong + phat + thu) * 1e4) / 1e4 };
}

const blend = (a, b, k) => ({ P: mixA(a.P, b.P, k), T: mixA(a.T, b.T, k), sp: mixA(a.sp, b.sp, k), lT: mixA(a.lT, b.lT, k), lP: mixA(a.lP, b.lP, k), h: mix(a.h, b.h, k), lift: mix(a.lift, b.lift, k) });

/**
 * Tư thế của chiêu `id` tại giây `t` kể từ lúc bắt đầu gồng. Trả { phase: 'gong'|'phat'|'thu', k (0..1 trong khung), w (trọng số hòa với tư thế thường 0..1), ...khung } hoặc null nếu chiêu lạ / đã xong (t ≥ tổng).
 * Gồng: nhích dần vào thế gồng (hơi chậm lúc đầu); Phát: bật nhanh sang thế phát; Thu: giữ thế phát rồi hạ dần về khung thu.
 * w tăng từ 0 ở đầu gồng và giảm về 0 ở cuối khung thu để không giật khi vào/ra tư thế.
 */
export function castSample(id, t) {
  const L = castTimeline(id); if (!L) return null;
  const tt = Number.isFinite(+t) ? +t : 0; if (tt < 0 || tt >= L.tong) return null;
  const P = POSE[id], wIn = sm(tt / Math.min(0.18, L.gong)), wOut = sm((L.tong - tt) / Math.min(0.2, L.thu * 0.6));
  let phase, k, f;
  if (tt < L.gong) { phase = 'gong'; k = tt / L.gong; f = P.gong; }
  else if (tt < L.gong + L.phat) { phase = 'phat'; k = (tt - L.gong) / L.phat; f = blend(P.gong, P.phat, 1 - (1 - k) * (1 - k)); }   // bật nhanh (ease-out)
  else { phase = 'thu'; k = (tt - L.gong - L.phat) / L.thu; f = blend(P.phat, P.thu, sm(k / 0.6)); }
  return { phase, k, w: Math.min(wIn, wOut), ...f };
}

const flat = (leg, knee) => { const d = -leg.x - knee; return { x: clamp(d < 0 ? d * 0.55 : d, -0.6, 0.6), y: 0, z: 0 }; };
/** Tư thế xương đầy đủ của một khung (chưa hòa với tư thế thường): cùng khóa với chibiPose trả về. hipsDrop tính từ chân để bàn chân chạm đất. */
export function framePose(f) {
  const zd = clamp(0.08 + 1.7 * f.h, 0, 0.6);
  const legL = { x: f.lT[0], y: 0, z: zd }, legR = { x: f.lP[0], y: 0, z: -zd }, shinL = kneeAngle(f.lT[1], 0), shinR = kneeAngle(f.lP[1], 0);
  const footL = flat(legL, shinL.x), footR = flat(legR, shinR.x);
  const out = {
    spine: { x: f.sp[0], y: f.sp[1], z: f.sp[2] },
    armL: armAngle(1, f.T[0], f.T[1]), armR: armAngle(-1, f.P[0], f.P[1]),
    foreL: elbowAngle(1, f.T[2], f.T[3]), foreR: elbowAngle(-1, f.P[2], f.P[3]),
    handL: wristAngle(1, f.T[2]), handR: wristAngle(-1, f.P[2]),
    legL, legR, shinL, shinR, footL, footR, hipsDrop: 0,
  };
  const yMin = Math.min(legPoints(out, 1).sole[1], legPoints(out, -1).sole[1]);
  out.hipsDrop = Math.max(0, LM.crotch * CHIBI_H + yMin);
  return out;
}

/** Hòa tư thế chiêu `f` (kết quả castSample) lên tư thế thường `q` (kết quả chibiPose/applyStance). f = null → trả q. Không sửa q. */
export function applyCast(q, f) {
  if (!f || !(f.w > 0)) return q;
  const c = framePose(f), w = f.w, out = { ...q };
  for (const k of ['spine', 'armL', 'armR', 'foreL', 'foreR', 'handL', 'handR', 'legL', 'legR', 'shinL', 'shinR', 'footL', 'footR']) out[k] = mixV(q[k], c[k], w);
  out.hipsDrop = mix(q.hipsDrop || 0, c.hipsDrop, w);
  return out;
}
